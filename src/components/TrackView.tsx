"use client";

import { useEffect } from "react";
import { track } from "@/lib/stat";

/**
 * Отметка о просмотре страницы, на которую приходят извне: карточка товара из
 * мессенджера и чужой вишлист. Серверные страницы о себе сообщить не могут —
 * ни куки, ни скриптов, — поэтому отметку ставит крошечный клиентский кусок.
 *
 * Виральность считается именно здесь: сколько людей открыло присланную ссылку
 * и сколько из них осталось свайпать.
 */
export default function TrackView({ kind }: { kind: "item" | "gift" }) {
  useEffect(() => {
    track("view", { kind });
  }, [kind]);
  return null;
}
