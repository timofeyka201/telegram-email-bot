/**
 * Идентификатор товара без суффикса круга.
 *
 * Когда каталог заканчивается, лента идёт по второму кругу, и карточки
 * получают суффикс («ae-123-r1»), иначе они совпали бы с уже показанными и
 * React отказался бы их различать. Но товар за ними стоит тот же самый,
 * поэтому везде, где речь о товаре, а не о позиции в ленте — в отмене, в
 * сверке цен, в поиске по ссылке, — суффикс нужно отбросить.
 */
export function baseId(id: string): string {
  return id.replace(/-r\d+$/, "");
}

/** Один и тот же товар, даже если карточки из разных кругов. */
export function sameProduct(a: string, b: string): boolean {
  return baseId(a) === baseId(b);
}
