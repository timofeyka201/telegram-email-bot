/** Бесконечная лента для демо-режима: повторяем подборку с новыми id. */
export function demoDeck(count = 24): Product[] {
  const out: Product[] = [];
  for (let i = 0; i < count; i++) {
    const base = DEMO_PRODUCTS[i % DEMO_PRODUCTS.length];
    out.push(i < DEMO_PRODUCTS.length ? base : { ...base, id: `${base.id}-${i}` });
  }
  return out;
}
