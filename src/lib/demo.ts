/**
 * Встроенная подборка на случай, когда токен не задан или парсер недоступен:
 * приложение всегда можно открыть и пощупать свайпы, не тратя запросы к API.
 */

const img = (seed: string, i: number, label = "") =>
  `/api/placeholder?seed=${encodeURIComponent(seed + i)}&i=${i}&label=${encodeURIComponent(label)}`;

function reviews(seed: string, texts: [string, number][]): Review[] {
  return texts.map(([text, rating], i) => ({
    id: `${seed}-r${i}`,
    author: ["Алексей", "Марина", "Дмитрий", "Ольга", "Ирина", "Павел"][i % 6],
    rating,
    text,
    date: `2026-0${(i % 8) + 1}-1${i % 9}`,
    images: i % 3 === 0 ? [img(seed, 90 + i)] : [],
  }));
}

