const PREPARED = FACETS.map(([group, values]) => [group, values.map(([tag, words]) => [tag, prepare(words)])]);

const AUDIENCE_TAG = { women: "женское", men: "мужское", kids: "детское" };

/**
 * Метки товара по названию: массив вида `["пол:женское", "материал:кожа"]`.
 * Пустой, если название ничего не выдало, — так бывает чаще, чем кажется.
 */
export function tagsByTitle(title) {
  const hay = normalize(title);
  const out = [];

  const who = AUDIENCE_TAG[audienceByTitle(title)];
  if (who) out.push(`пол:${who}`);

  for (const [group, values] of PREPARED) {
    for (const [tag, words] of values) {
      if (words.some((w) => hay.includes(w))) {
        out.push(`${group}:${tag}`);
        break;
      }
    }
  }
  return out;
}
