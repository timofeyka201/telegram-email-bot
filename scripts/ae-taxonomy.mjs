/**
 * Категория товара по его названию — и раздел, в который эта категория входит.
 *
 * Площадка категорию не присылает: у нас она берётся из ящика, из которого
 * товар достали, — из фида и его раздела. Поэтому платье, лежащее в фиде
 * «Дом и сад», так и остаётся «Домом и садом», а «Инструменты» вмещают
 * отвёртки, садовые шланги и автомобильные насосы разом.
 *
 * Название — сигнал надёжнее. Оно у AliExpress перегружено ключевыми
 * словами, но именно поэтому нужное слово в нём почти всегда есть.
 *
 * Уровней два. Нижний — что это за вещь («Купальники», «Футболки и
 * рубашки»). Верхний — кому она: купальник попадает в «Женскую одежду»,
 * футболка с «мужская» в названии — в «Мужскую», та же футболка с «детская» —
 * в «Детскую». Без указания в названии вещь остаётся в бесполой «Одежде»:
 * выдумывать пол за продавца мы не беремся.
 *
 * Правила проверяются сверху вниз, побеждает первое подошедшее, поэтому
 * частное стоит выше общего: «чехол для телефона» должен стать аксессуаром
 * раньше, чем «телефоном». Слово ищется началом слова в названии, так что
 * «платья» и «платье» ловятся одинаково, а «плательщик» — нет, потому что
 * таких слов в товарных названиях не бывает. Если начала мало и слово цепляет
 * лишнее — «стол» в «столовых салфетках», — впереди ставится «=»: тогда
 * слово должно совпасть целиком.
 */

/** Нижний регистр, ё как е, всё кроме букв и цифр — пробел. */
export function normalize(text) {
  return ` ${String(text ?? "").toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я0-9]+/gi, " ").trim()} `;
}

/** `слово` — начало слова, `=слово` — слово целиком. */
function prepare(words) {
  return words.map((w) =>
    w.startsWith("=") ? ` ${normalize(w.slice(1)).trim()} ` : ` ${normalize(w).trim()}`,
  );
}

