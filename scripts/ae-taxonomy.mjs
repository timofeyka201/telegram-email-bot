const PREPARED = RULES.map(([category, words]) => [category, words.map((w) => ` ${normalize(w).trim()}`)]);

/**
 * Категория по названию или undefined, если ни одно правило не подошло —
 * тогда остаётся та, что досталась от фида.
 */
export function categoryByTitle(title) {
  const hay = normalize(title);
  for (const [category, words] of PREPARED) {
    for (const word of words) {
      if (hay.includes(word)) return category;
    }
  }
  return undefined;
}
