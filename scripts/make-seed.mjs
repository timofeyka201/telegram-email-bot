const PER_CAT = Math.ceil(1000 / CATS.length);

function reviewsFor(id, title, rating) {
  const good = [
    "Пришло быстро, упаковано аккуратно. Соответствует описанию.",
    "Пользуюсь вторую неделю — нареканий нет, качество за свои деньги отличное.",
    "Взял по акции, доволен. Брал бы ещё раз.",
    "Всё как на фото, придраться не к чему.",
  ];
  const mid = [
    "В целом нормально, но ожидал чуть лучше за эти деньги.",
    "Работает, но есть мелкие огрехи в отделке.",
    "Нормально, хотя инструкция на русском была бы кстати.",
  ];
  const bad = ["Не подошло, оформил возврат без проблем.", "Пришло с дефектом, заменили."];
  const n = int(2, 5);
  return Array.from({ length: n }, (_, i) => {
    const r = rating >= 4.5 ? (rnd() > 0.2 ? 5 : 4) : rating >= 4 ? (rnd() > 0.35 ? 5 : 3) : int(2, 4);
    const text = r >= 5 ? pick(good) : r >= 3 ? pick(mid) : pick(bad);
    return {
      id: `${id}-r${i}`,
      author: pick(["Алексей", "Марина", "Дмитрий", "Ольга", "Ирина", "Павел", "Светлана", "Никита"]),
      rating: r, text, date: `2026-0${int(1, 9)}-${String(int(10, 28))}`, images: [],
    };
  });
}

const products = [];
for (const cat of CATS) {
  for (let i = 0; i < PER_CAT && products.length < 1000; i++) {
    const brand = pick(cat.b);
    const line = pick(cat.l);
    const id = `seed-${String(products.length + 1).padStart(4, "0")}`;
    const price = int(cat.p[0], cat.p[1]);
    const hasDiscount = rnd() > 0.35;
    const oldPrice = hasDiscount ? Math.round(price * (1.15 + rnd() * 0.6)) : undefined;
    const rating = Math.round((38 + rnd() * 12)) / 10;
    const title = `${cat.n} ${brand} ${line}, модель ${int(100, 9999)}`;

    products.push({
      id,
      title,
      category: cat.n,
      brand,
      // Ссылки на несуществующие карточки не выдумываем: ведём на поиск.
      url: `https://www.wildberries.ru/catalog/0/search.aspx?search=${encodeURIComponent(`${cat.n} ${brand}`)}`,
      images: [1, 2, 3, 4].map((n) => `/api/placeholder?seed=${id}${n}&i=${n}&label=${encodeURIComponent(cat.n)}`),
      price,
      priceMax: oldPrice,
      tiers: [{ from: 1, price }],
      minOrder: 1,
      description: cat.d(brand, line),
      attributes: [...cat.a(), ["Бренд", brand], ["Страна производства", pick(COUNTRIES)]]
        .map(([name, value]) => ({ name, value: String(value) })),
      skus: some(Array.from({ length: 5 }, () => cat.v()), int(2, 4)).map((name, k) => ({ id: `${id}-s${k}`, name })),
      seller: { name: `${brand} Store`, rating: Math.round((40 + rnd() * 10)) / 10 },
      rating,
      reviewsCount: int(12, 9000),
      soldCount: rnd() > 0.4 ? int(50, 40000) : undefined,
      reviews: reviewsFor(id, title, rating),
      currency: "RUB",
      source: "local",
    });
  }
}

