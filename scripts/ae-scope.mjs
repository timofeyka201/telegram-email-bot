/**
 * Границы витрины: что вообще держим в каталоге.
 *
 * Витрина сузилась до одежды, аксессуаров и того, что для дома. Дрели,
 * корм для кошек и автомобильные компрессоры из каталога ушли — и дело не
 * в том, что они плохие: лента, в которой рядом лежат платье и перфоратор,
 * никому не подходит целиком, а место на диске и в памяти конечно.
 *
 * Правило одно и то же в двух местах: им чистят накопленный снапшот
 * (`scripts/keep-groups.mjs`) и им же импортёр отсекает лишнее на входе,
 * чтобы каталог не набирался заново тем, что вчера удалили.
 */

/**
 * Разделы, которые остаются. Значение `true` — раздел целиком, набор строк —
 * только перечисленные категории внутри него.
 */
export const SCOPE = {
  "Женская одежда": true,
  "Мужская одежда": true,
  Одежда: true,
  Аксессуары: true,
  Дом: new Set(["Для дома", "Кухня"]),
};

/**
 * Карточка в границах витрины?
 *
 * `keepUnknown` — что делать с товаром, которому раздел не достался:
 * название ни о чём не сказало правилам. В накопленном снапшоте такие
 * оставляют (запросы на них уже потрачены, картинки скачаны, и среди них
 * есть настоящая одежда, просто неопознанная), а на входе отсекают — иначе
 * ограничение ничего не ограничивает: неопознанной приезжает треть всего
 * подряд.
 */
export function inScope(product, { keepUnknown = false } = {}) {
  const group = product?.group;
  if (!group) return keepUnknown;
  const allowed = SCOPE[group];
  if (!allowed) return false;
  if (allowed === true) return true;
  return product.category ? allowed.has(product.category) : false;
}

/** Человекочитаемое описание границ — для вывода скриптов. */
export function scopeLines() {
  return Object.entries(SCOPE).map(([group, allowed]) =>
    allowed === true ? `${group} — целиком` : `${group} — только ${[...allowed].join(", ")}`,
  );
}
